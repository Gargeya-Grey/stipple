// Any glyph but the blank, cycling fast: the look of a cell being worked out.
const busy = (seed: number) => 1 + floor(fract(seed + time * 9) * 30.99)

// The pointer's stroke: heat laid along the path from where it was to where it is, fading over about a second.
const trail: Buffer = buffer({ scale: 1 / CELL, float: 16, filter: 'nearest' }, p => {
  let heat = trail.at(p.cell).r * exp(-dt * 1.1)
  for (const f of pointers) {
    const moved = length(vec2(f.at - f.was))
    const aim = vec2((f.at - f.was) / max(moved, 0.01))
    const from = vec2(p.point - f.was)
    const along = dot(from, aim)
    const beyond = max(max(-along, along - moved), 0)
    const away = max(dot(from, from) - along * along, 0) + beyond * beyond
    const live = 1 - smoothstep(0, 0.3, f.gone)
    heat = heat + exp(-away / 260) * min(moved / 3, 1) * live * 0.6 * freeOf(f.over)
  }
  return vec4(min(heat, 1), 0, 0, 1)
})

// The last press on the bare backdrop: where (x, y), when (z), and whether a pointer was down last frame (w).
// A press on the app itself (a button, the text) sends no ripple.
const tap: Buffer = buffer({ size: [1, 1], float: 32, filter: 'nearest' }, () => {
  if (first) {
    return vec4(0, 0, -100, 0)
  }
  const prev = tap.at(vec2(0, 0))
  let s = vec4(prev.x, prev.y, prev.z, 0)
  let down = 0
  for (const f of pointers) {
    if (f.down > 0.5 && prev.w < 0.5 && f.over < 0.5) {
      s = vec4(f.at.x, f.at.y, time, 0)
    }
    down = max(down, f.down)
  }
  s.w = down
  return s
})

// Spirits: each wanders a patch of the margins and, when a pointer comes near, flies to circle it.
const flies: Buffer = buffer({ size: [FLIES, 1], float: 32, filter: 'nearest' }, p => {
  const i = p.cell.x
  const right = step(0.5, fract(i * 0.5))
  const sx = acrossMargin(right + 0.1 + 0.75 * fract(i * 0.618), marginsOf())
  const sy = 0.12 + 0.48 * fract(i * 0.382 + 0.2)
  const home = vec2(size.x * sx + 46 * sin(time * 0.21 + i * 1.7), size.y * sy + 38 * sin(time * 0.17 + i * 2.3))
  if (first || fresh) {
    return vec4(home, 0, 0)
  }
  const was = flies.at(p.cell).xy
  let target = home
  let pull = 0
  for (const f of pointers) {
    const live = clamp(1 - f.gone, 0, 1)
    const near = smoothstep(360, 120, length(vec2(was - f.at))) * live * freeOf(f.over)
    const turn = time * (0.9 + 0.08 * i) + i * 0.524
    const orbit = vec2(sin(turn + 1.571), sin(turn)) * (30 + 3 * i)
    if (near > pull) {
      pull = near
      target = vec2(mix(home, f.at + orbit, near))
    }
  }
  const pos = vec2(was + (target - was) * (1 - exp(-dt * (0.6 + 2.6 * pull))))
  return vec4(pos, pull, 0)
})

// Which glyph each cell shows, what kind it is, how bright and how much it glows.
const art: Buffer = buffer({ scale: 1 / CELL, float: 16, filter: 'nearest' }, p => {
  const cx = p.cell.x
  const cy = p.cell.y
  const cols = art.size.x
  const rows = art.size.y
  const cellSize = vec2(size / art.size)
  const at = p.point
  const u = p.uv
  const h = scramble(cx, cy)
  const r1 = part(h, 0)
  const r2 = part(h, 8)
  const r3 = part(h, 16)
  const r4 = part(h, 24)
  // 0 behind the conversation column, 1 out in the margins.
  const m = marginsOf()
  const halfColumn = (m.z - m.y) * 0.5
  const calm = smoothstep(halfColumn - 0.04, halfColumn + 0.1, abs(u.x - (m.y + m.z) * 0.5))
  const inComposer = step(composer.x - 0.02, u.x) * step(u.x, composer.z + 0.02) * step(u.y, composer.w + 0.02)

  let g = 0
  let k = 0
  let b = 0
  let glow = 0

  // Specks: stars by night, paper fibres by day. The top-left cell stays bare for dayOf.
  const corner = step(rows - 1.5, cy) * step(cx, 0.5)
  if (r1 < 0.03 * (0.25 + 0.75 * calm) * (0.3 + u.y) && corner < 0.5) {
    g = r2 < 0.75 ? G_DOT : r2 < 0.92 ? G_TICK : G_PLUS
    k = 0
    b = 0.35 + 0.45 * (0.5 + 0.5 * sin(time * (0.7 + r3 * 1.6) + r4 * 40))
  }

  // The far forest: a low line of small cedars along the foot, taller towards the margins, grown at the start.
  if (inComposer < 0.5) {
    if (cy < 0.5) {
      g = r1 < 0.5 ? G_UNDER : r1 < 0.8 ? G_COMMA : G_DOT
      k = 1
      b = 0.7
    }
    const tc = floor(cx / 7)
    const grown = clamp(time * 0.5 - 0.3 - part(scramble(tc, 5), 0) * 0.6, 0, 1)
    const th = ((4 + 7 * part(scramble(tc, 3), 0)) * (0.55 + 0.6 * calm) + 2) * grown
    const fdx = abs(cx - tc * 7 - 3)
    const fdy = cy - 1
    if (fdy >= 0 && fdy <= th - 1 && fdx <= (th - fdy) * 0.5) {
      g = fdy >= th - 1.5 ? G_CARET : fdx >= (th - fdy) * 0.5 - 0.6 ? (cx < tc * 7 + 3 ? G_SLASH : G_BACK) : r2 < 0.5 ? G_COLON : G_A
      k = 1
      b = 0.8
    }
  }

  // Mist drifts across the lower third.
  const band = smoothstep(0.06, 0.12, u.y) * (1 - smoothstep(0.28, 0.36, u.y))
  const swirl = sin(at.x * 0.011 + time * 0.22 + sin(at.y * 0.04) * 1.5) * sin(at.x * 0.006 - time * 0.15 + at.y * 0.023)
  const mist = smoothstep(0.25, 0.65, swirl) * band * (0.35 + 0.65 * calm)
  if (mist > r3 + 0.05 + 0.3 * step(0.5, g)) {
    g = r1 < 0.6 ? G_TILDE : G_DASH
    k = 3
    b = mist
  }

  // Near cedars, placed along the margins and drawn back to front: a far one is dimmer. A wind front flips their
  // needles as it passes; they sway, and lean away from a pointer.
  const wind = 0.5 + 0.5 * sin(time * 0.9 - at.x * 0.006 + at.y * 0.002)
  for (let t = 0; t < 7; t++) {
    const tree = TREES.at(t)
    const trunkX = floor(acrossMargin(tree.x, m) * cols)
    const tall = floor(tree.y * rows)
    const crown = vec2((trunkX + 0.5) * cellSize.x, (tall * 0.6 + 1) * cellSize.y)
    let lean = 0
    for (const f of pointers) {
      const off = vec2(crown - f.at)
      lean = lean + sign(off.x) * exp(-dot(off, off) / 60000) * (1 - min(f.gone * 2, 1)) * 3 * freeOf(f.over)
    }
    const dy = cy - 1
    const lift = dy / max(tall, 1)
    const sway = sin(time * 0.8 + tree.z * 6.3) * 0.7 + lean
    const dx = cx - trunkX - floor(sway * lift * lift + 0.5)
    const grown = clamp((time - 0.6 - tree.z * 1.2) * 0.45, 0, 1)
    const reach = tall * grown
    const trunkTop = max(2, tall * 0.12)
    const adx = abs(dx)
    if (dy >= 0 && dy < reach) {
      const rel = reach - dy
      const wide = rel * 0.42 * (0.7 + 0.3 * fract(rel / 5)) + 0.3
      if (dy >= trunkTop * 0.7 && adx <= wide) {
        const leaf = floor(fract(r3 + tree.z + wind * 0.6 + time * 0.04) * 5)
        const needle = leaf < 1 ? G_CARET : leaf < 2 ? G_A : leaf < 3 ? G_STAR : leaf < 4 ? G_PCT : G_HASH
        g = rel <= 1 ? G_CARET : adx > wide - 1 ? (dx < 0 ? G_SLASH : G_BACK) : needle
        k = 2
        b = (0.78 + 0.22 * wind) * mix(0.5, 1, tree.w)
      } else if (dy < trunkTop && adx < 0.5) {
        g = G_PIPE
        k = 6
        b = 0.9 * mix(0.5, 1, tree.w)
      } else if (dy < 0.5 && adx < 1.5) {
        g = dx < 0 ? G_SLASH : G_BACK
        k = 6
        b = 0.9 * mix(0.5, 1, tree.w)
      }
    }
  }

  // The torii, built bottom-up from its characters when the session opens. It glows when a pointer comes near,
  // and a press anywhere makes it pulse.
  const gx0 = cols - 27
  const gy0 = rows - 5
  const gateMid = vec2((gx0 + 12) * cellSize.x, (gy0 - 9) * cellSize.y)
  let nearGate = 0
  for (const f of pointers) {
    nearGate = max(nearGate, smoothstep(300, 70, length(vec2(f.at - gateMid))) * (1 - min(f.gone * 2, 1)) * freeOf(f.over))
  }
  let onGate = 0
  const pressed = tap.at(vec2(0, 0))
  const since = time - pressed.z
  const pulse = exp(-since * 1.5) * step(0, since)
  const gx = cx - gx0
  const gr = gy0 - cy
  if (gx >= 0 && gx < 24 && gr >= 0 && gr < 18) {
    const line = TORII.at(gr)
    const wi = floor(gx / 6)
    const word = wi < 1 ? line[0] : wi < 2 ? line[1] : wi < 3 ? line[2] : line[3]
    const tg = signed(int((word >>> int((gx - wi * 6) * 5)) & 31))
    const built = clamp((time - 1.2 - (17 - gr) * 0.12 - r1 * 0.4) * 2.5, 0, 1)
    if (tg > 0.5 && built > 0) {
      const tablet = step(3, gr) * step(gr, 4) * step(10, gx) * step(gx, 13)
      const ground = step(16.5, gr)
      const wave = fract(time * 0.5 - gr * 0.06 - gx * 0.025)
      const rebuild = step(0.3, nearGate) * step(wave, 0.07) * step(14.5, tg) * step(tg, 15.5)
      onGate = 1
      g = built < 1 ? busy(r2) : rebuild > 0.5 ? (r2 < 0.5 ? G_PCT : G_AMP) : tg
      k = ground > 0.5 ? 1 : tablet > 0.5 ? 6 : 4
      b = 1
      glow = (0.28 + 0.1 * sin(time * 0.8 + gr * 0.3) + nearGate * 0.6 + pulse * 0.5) * (1 - ground)
    }
    // Between the pillars, small lights pass through the gate, more of them when a pointer is near.
    if (tg < 0.5 && gx >= 7 && gx <= 16 && gr >= 6 && gr <= 15) {
      const drift = fract(r2 + time * (0.05 + 0.1 * r3))
      if (r1 < 0.05 + 0.3 * nearGate && drift < 0.6) {
        g = r4 < 0.6 ? G_DOT : G_STAR
        k = 5
        b = 0.5 + 0.5 * sin(drift * 5.2)
        glow = b * 0.6
      }
    }
  }

  // Orange leaves fall from the gate's crown, turning as they go; a pointer blows them aside.
  for (let i = 0; i < LEAVES; i++) {
    const s1 = part(scramble(i, 41), 0)
    const s2 = part(scramble(i, 43), 8)
    const fall = fract(time / (10 + 6 * s1) + s2)
    const startX = (gx0 + 3 + 18 * s1) * cellSize.x
    const startY = (gy0 - 1) * cellSize.y
    let leaf = vec2(startX - fall * size.x * 0.22 + sin(fall * 9 + i) * 34, startY - fall * startY * 0.85)
    for (const f of pointers) {
      const off = vec2(leaf - f.at)
      leaf = vec2(leaf + off * 1.2 * exp(-dot(off, off) / 18000) * (1 - min(f.gone * 2, 1)) * freeOf(f.over))
    }
    const lc = floor(vec2(leaf / cellSize))
    // A leaf passes behind the gate, never over its characters.
    if (abs(lc.x - cx) < 0.5 && abs(lc.y - cy) < 0.5 && onGate < 0.5) {
      const spin = fract(time * 1.3 + i * 0.37)
      g = spin < 0.25 ? G_STAR : spin < 0.5 ? G_COMMA : spin < 0.75 ? G_TICK : G_SEMI
      k = 7
      b = 1 - 0.6 * fall
      glow = 0.45 * (1 - fall)
    }
  }

  // Spirits: a star in their cell and a soft glow round it.
  for (let i = 0; i < FLIES; i++) {
    const fly = flies.at(vec2(i, 0))
    const d = length(vec2(at - fly.xy))
    const blink = 0.55 + 0.45 * sin(time * (1.6 + 0.2 * i) + i * 2.1)
    // Exactly one cell, the one the spirit is in: a distance test lights two cells when it sits between them.
    const home = floor(vec2(fly.xy / cellSize))
    if (abs(home.x - cx) < 0.5 && abs(home.y - cy) < 0.5) {
      g = fly.z > 0.4 ? G_STAR : G_PLUS
      k = 5
      b = blink
      glow = max(glow, blink)
    } else if (g < 0.5) {
      const near = exp(-(d * d) / 700) * blink * 0.8
      if (near > glow) {
        glow = near
        k = 5
      }
    }
  }

  // The lantern: a ring of characters being worked out follows the pointer; inside it, what is there brightens and
  // a hidden layer of characters shows.
  for (const f of pointers) {
    const live = clamp(f.age * 3, 0, 1) * (1 - smoothstep(0, 0.6, f.gone)) * freeOf(f.over)
    const d = length(vec2(at - f.at))
    // Small and quiet at rest; the ring of characters being worked out shows only while the pointer moves.
    const moving = smoothstep(0.5, 6, length(vec2(f.at - f.was)))
    const inside = smoothstep(72, 24, d) * live
    const edge = d - 64
    const ring = exp(-(edge * edge) / 90) * live * moving
    if (g > 0.5) {
      b = max(b, inside)
      glow = max(glow, inside * 0.4)
    } else if (r4 < 0.22 * inside) {
      g = r3 < 0.25 ? G_KI : r3 < 0.4 ? G_YAMA : r3 < 0.5 ? G_HITO : r3 < 0.7 ? G_COLON : r3 < 0.85 ? G_DOT : G_PLUS
      k = 5
      b = inside * 0.7
      glow = max(glow, inside * 0.15)
    }
    if (ring > 0.4 && r1 < 0.3) {
      g = busy(r2)
      k = 5
      b = max(b, ring * 0.8)
      glow = max(glow, ring * 0.3)
    }
  }

  // The stroke: sparks where the pointer has just passed; cedars it brushes turn to leaf light.
  const heat = trail.at(p.cell).r
  if (heat > 0.08) {
    if (g < 0.5 && r3 < heat * 0.6) {
      const spark = fract(r2 + time * 3)
      g = spark < 0.3 ? G_STAR : spark < 0.6 ? G_PLUS : spark < 0.8 ? G_TICK : G_DOT
      k = 5
      b = heat
    } else if (heat > 0.45) {
      k = 5
    }
    glow = max(glow, heat)
  }

  // A press sends a thin ring of characters out, fading within about a second, a few hundred points out.
  const rim = length(vec2(at - pressed.xy)) - since * 220
  const ripple = exp(-(rim * rim) / 120) * exp(-since * 2.2) * step(0, since)
  if (ripple > 0.3 && r2 < 0.45) {
    g = busy(r3)
    k = r1 < 0.5 ? 4 : 5
    b = max(b, ripple)
    glow = max(glow, ripple * 0.5)
  }

  return vec4(g / 32, k / 8, clamp(b, 0, 1), clamp(glow, 0, 1))
})

// The glow, leaf and warm apart, kept with mipmaps so the picture can read it blurred.
const halo: Buffer = buffer({ scale: 1 / CELL, float: 16, filter: 'mipmap' }, p => {
  const a = art.at(p.cell)
  const kind = floor(a.g * 8 + 0.5)
  const warm = step(3.5, kind) * step(kind, 4.5) + step(6.5, kind)
  const leafy = step(4.5, kind) * step(kind, 5.5)
  return vec4(a.a * leafy, a.a * warm, 0, 1)
})

const field = picture(p => {
  const day = dayOf()
  const grid = art.size
  const t = floor(vec2(p.uv * grid))
  const cellSize = vec2(size / grid)
  const local = vec2((p.uv * grid - t) * cellSize)
  const a = art.at(t)
  const gi = floor(a.r * 32 + 0.5)
  const kind = floor(a.g * 8 + 0.5)

  // The glyph's pixels are 1.5 points square, centred in the cell; row 0 is the glyph's top.
  const col = floor((local.x - 2.25) / 1.5)
  const row = 6 - floor((local.y - 0.75) / 1.5)
  const inBox = step(0, col) * step(col, 4) * step(0, row) * step(row, 6)
  const glyph = FONT.at(gi)
  const word = row < 3.5 ? glyph[0] : glyph[1]
  const shift = int(row < 3.5 ? row * 5 + col : (row - 4) * 5 + col)
  const bit = signed(int((word >>> shift) & 1)) * inBox

  const base = vec3(mix(INK_DARK.at(kind), INK_LIGHT.at(kind), day))
  const hot = vec3(mix(HOT_DARK.at(kind), HOT_LIGHT.at(kind), day))
  const ink = vec3(mix(base, hot, a.a * 0.75))

  // A tight glow and a faint wide one; a strong wide one prints as round smudges.
  const bloom = vec4(halo.sample(p.uv, 1) + halo.sample(p.uv, 2) * 0.35)
  const paper = vec3(mix(vec3(0.102, 0.125, 0.118), vec3(0.965, 0.969, 0.957), day))
  const leafBloom = vec3(mix(vec3(0.12, 0.42, 0.31), vec3(0.75, 0.9, 0.83), day))
  const warmBloom = vec3(mix(vec3(0.5, 0.22, 0.1), vec3(1, 0.82, 0.7), day))

  let color = vec3(mix(paper, leafBloom, clamp(bloom.r * 0.5, 0, 0.6)))
  color = vec3(mix(color, warmBloom, clamp(bloom.g * 0.45, 0, 0.55)))
  color = vec3(mix(color, ink, bit * a.b))
  return vec4(color, 1)
})

export default shader({ fps: 30, passes: [trail, tap, flies, art, halo, field] })
