// Two whole numbers in, 32 scrambled bits out. tools/build.mjs has the same mixer, so the still picture matches.
const scramble = (a: number, b: number) => {
  let h = int(int(a) * 3471823 + int(b) * 5908417 + 733)
  h = int(h ^ (h >>> 17))
  h = int(h * 93827461)
  h = int(h ^ (h >>> 11))
  h = int(h * 2753197)
  h = int(h ^ (h >>> 14))
  return h
}
const part = (h: number, shift: number) => signed(int((int(h) >>> shift) & 255)) / 256

// The Svg is printed in the window's mode, and its top-left corner is always bare ground.
const dayOf = () => step(0.5, dot(scene.sample(vec2(0.002, 0.998)).rgb, vec3(0.3, 0.6, 0.1)))

// The margins beside the conversation, as shares of the backdrop's width: the pane's left edge (the backdrop runs
// on under a sidebar), then the prompt box's left and right edges. The prompt box sits in the middle of the pane.
// Where the app does not say where the prompt box is, the left margin starts at 12%, so that a sidebar of up to
// about that width hides none of the left cedars.
const marginsOf = () => {
  const known = step(0.1, composer.z - composer.x)
  return vec4(mix(0.12, clamp(composer.x + composer.z - 1, 0, 0.45), known), mix(0.32, composer.x, known), mix(0.72, composer.z, known), 0)
}
// A place along the margins: 0 to 1 crosses the left margin from its outer edge, 1 to 2 the right one.
const acrossMargin = (pos: number, m: vec4) => (pos < 1 ? m.x + pos * (m.y - m.x) : 1 - (pos - 1) * (1 - m.z))
// Pointer effects are for the margins: over the conversation or the prompt box they nearly stop.
const freeOf = (over: number) => 1 - 0.9 * over

